// Turns load-run JSON files into one readable report (Markdown and HTML) under docs/evidence/r3-load/.
//   node report.mjs <name> <label> [<label> ...]   e.g.  node report.mjs LOAD-REPORT before after live
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = resolve(dirname(fileURLToPath(import.meta.url)), '../../docs/evidence/r3-load');
const [name, ...labels] = process.argv.slice(2);
if (!name || !labels.length) {
  console.error('usage: node report.mjs <report name> <label> [<label> ...]');
  process.exit(2);
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const md = [];
const html = [];
const heading = (level, text) => { md.push(`${'#'.repeat(level)} ${text}\n`); html.push(`<h${level}>${esc(text)}</h${level}>`); };
const para = (text) => { md.push(`${text}\n`); html.push(`<p>${esc(text)}</p>`); };
const table = (head, rows) => {
  md.push(`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`), '');
  html.push(`<table><thead><tr>${head.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${rows.map((r) => `<tr>${r.map((c) => `<td>${esc(c)}</td>`).join('')}</tr>`).join('')}</tbody></table>`);
};
const v = (x) => (x === null || x === undefined ? '-' : x);

heading(1, `Load report: ${name}`);
para('Synthetic @example.com accounts, AI_PROVIDER=stub, autocannon 8.0.0. Latencies are in milliseconds and are measured by the load tool at the client. Generated by scripts/load/report.mjs from the JSON files named below.');

for (const label of labels) {
  const r = JSON.parse(readFileSync(resolve(dir, `${label}.json`), 'utf-8'));
  heading(2, `${label}: ${r.meta.profile} / ${r.meta.scenario} on ${r.meta.target}`);
  para(`Started ${r.meta.startedAt}; commit ${r.meta.commit}; ${r.meta.machine.cpus} logical CPUs (${r.meta.machine.model}), ${r.meta.machine.totalMemGb} GB; Node ${r.meta.node}.${r.meta.poolMax ? ` Database pool max forced to ${r.meta.poolMax}.` : ''}${r.meta.note ? ` ${r.meta.note}` : ''}`);
  table(
    ['Phase', 'Connections', 'Req/s', 'p50', 'p95', 'p99', 'Errors %', 'Rate-limited (429)', 'Server CPU avg/max %', 'Loop delay p99 max', 'Pool used/max (waiting)'],
    r.phases.map((p) => [p.tag, p.connections, p.rps, v(p.p50), v(p.p95), v(p.p99), p.errorRate, p.rateLimited, p.server ? `${p.server.cpuAvgPct}/${p.server.cpuMaxPct}` : '-', p.server ? p.server.loopP99MsMax : '-', p.server ? `${v(p.server.poolTotalMax)}/${v(p.server.poolMax)} (${v(p.server.poolWaitingMax)})` : '-'])
  );
  if (r.meta.profile === 'ramp') {
    para(r.breaking
      ? `Breaking point: ${r.breaking.connections} connections (overall p95 ${r.breaking.p95} ms, errors ${r.breaking.errorRate}%). Slowest route there: ${r.breaking.worstRoute}.`
      : 'No step passed p95 2000 ms or 1% errors.');
  }
  if (r.liveLogins) {
    para('Sign-ins of the one synthetic live account, one at a time with 2 s between them.');
    table(['#', 'Status', 'ms'], r.liveLogins.map((l, i) => [i + 1, l.status, l.ms]));
  }
  const focus = r.breaking ? r.phases.find((p) => p.connections === r.breaking.connections) : r.phases.at(-1);
  const prior = r.breaking ? r.phases[r.phases.indexOf(focus) - 1] : null;
  for (const p of [prior, focus].filter(Boolean)) {
    heading(3, `Per route at ${p.connections} connections (${p.tag})`);
    table(
      ['Route', 'Count', 'Req/s', 'p50', 'p95', 'p99', 'Max', 'Errors', '429'],
      Object.entries(p.routes).sort((a, b) => b[1].p95 - a[1].p95).map(([route, s]) => [route, s.count, s.rps, s.p50, s.p95, s.p99, s.max, s.errors, s.rateLimited])
    );
  }
}

writeFileSync(resolve(dir, `${name}.md`), md.join('\n'));
const css = 'body{font:14px/1.5 system-ui,sans-serif;max-width:1100px;margin:2rem auto;padding:0 16px;color:#1b1f23;background:#fff}table{border-collapse:collapse;margin:1rem 0;width:100%;font-size:13px}th,td{border:1px solid #d0d7de;padding:4px 8px;text-align:right}th:first-child,td:first-child{text-align:left}th{background:#f6f8fa}@media(prefers-color-scheme:dark){body{background:#0d1117;color:#e6edf3}th{background:#161b22}th,td{border-color:#30363d}}';
writeFileSync(resolve(dir, `${name}.html`), `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Load report ${esc(name)}</title><style>${css}</style></head><body>${html.join('\n')}</body></html>`);
console.log(`wrote ${name}.md and ${name}.html`);
